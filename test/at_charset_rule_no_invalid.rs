const RULE_NAME: &str = "at-charset-rule-no-invalid";

fn rejected(reason: &str) -> String {
    format!("Invalid \"@charset\" rule, {reason}")
}

test_rule! {
    name: default_config,
    ruleName: RULE_NAME,
    config: [true],
    accept: [
        {
            code: "@charset \"utf-8\";",
        },
        {
            code: "@charset \"UTF-8\";",
        },
        {
            code: "@charset \"iso-8859-15\";",
        },
        {
            code: "@charset \"utf-8\";\na {}",
        },
    ],
    reject: [
        {
            code: "\u{FEFF}@charset \"utf-8\";",
            message: rejected("expected no byte order mark before it"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 18,
        },
        {
            code: " @charset \"utf-8\";",
            message: rejected("expected it to be at the very start of the stylesheet"),
            line: 1,
            column: 2,
            endLine: 1,
            endColumn: 19,
        },
        {
            code: "\n@charset \"utf-8\";",
            message: rejected("expected it to be at the very start of the stylesheet"),
            line: 2,
            column: 1,
            endLine: 2,
            endColumn: 18,
        },
        {
            code: "a {}\n@charset \"utf-8\";",
            message: rejected("expected it to be at the very start of the stylesheet"),
            line: 2,
            column: 1,
            endLine: 2,
            endColumn: 18,
        },
        {
            code: "/* comment */\n@charset \"utf-8\";",
            message: rejected("expected it to be at the very start of the stylesheet"),
            line: 2,
            column: 1,
            endLine: 2,
            endColumn: 18,
        },
        {
            code: "@CHARSET \"utf-8\";",
            message: rejected("expected it to be lowercase"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 18,
        },
        {
            code: "@Charset \"utf-8\";",
            message: rejected("expected it to be lowercase"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 18,
        },
        {
            code: "@charset  \"utf-8\";",
            message: rejected("expected a single space after it"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 19,
        },
        {
            code: "@charset\t\"utf-8\";",
            message: rejected("expected a single space after it"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 18,
        },
        {
            code: "@charset\n\"utf-8\";",
            message: rejected("expected a single space after it"),
            line: 1,
            column: 1,
            endLine: 2,
            endColumn: 9,
        },
        {
            code: "@charset\"utf-8\";",
            message: rejected("expected a single space after it"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 17,
        },
        {
            code: "@charset 'utf-8';",
            message: rejected("expected double quotes around the encoding label"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 18,
        },
        {
            code: "@charset utf-8;",
            message: rejected("expected double quotes around the encoding label"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 16,
        },
        {
            code: "@charset \"utf-8\" ;",
            message: rejected("expected a semicolon directly after the closing quote"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 19,
        },
        {
            code: "@charset \"utf-8\"",
            message: rejected("expected a semicolon directly after the closing quote"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 17,
        },
        {
            code: "@charset \"utf-8\" {}",
            message: rejected("expected a semicolon directly after the closing quote"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 20,
        },
        {
            code: "@charset \"utf-8\" extra;",
            message: rejected("expected a semicolon directly after the closing quote"),
            line: 1,
            column: 1,
            endLine: 1,
            endColumn: 24,
        },
        {
            code: "@charset;",
            warnings: [
                {
                    message: rejected("expected a single space after it"),
                    line: 1,
                    column: 1,
                    endLine: 1,
                    endColumn: 10,
                },
                {
                    message: rejected("expected double quotes around the encoding label"),
                    line: 1,
                    column: 1,
                    endLine: 1,
                    endColumn: 10,
                },
            ],
        },
        {
            code: " @CHARSET\t'utf-8' ;",
            warnings: [
                {
                    message: rejected("expected it to be at the very start of the stylesheet"),
                    line: 1,
                    column: 2,
                    endLine: 1,
                    endColumn: 20,
                },
                {
                    message: rejected("expected it to be lowercase"),
                    line: 1,
                    column: 2,
                    endLine: 1,
                    endColumn: 20,
                },
                {
                    message: rejected("expected a single space after it"),
                    line: 1,
                    column: 2,
                    endLine: 1,
                    endColumn: 20,
                },
                {
                    message: rejected("expected double quotes around the encoding label"),
                    line: 1,
                    column: 2,
                    endLine: 1,
                    endColumn: 20,
                },
                {
                    message: rejected("expected a semicolon directly after the closing quote"),
                    line: 1,
                    column: 2,
                    endLine: 1,
                    endColumn: 20,
                },
            ],
        },
    ],
}
